// Extract exactly the generated dependency lock from our own BuildKit tar export.
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';
const local = fileURLToPath(new URL('../.local/', import.meta.url));
const archive = await readFile(resolve(local, 'lock-export.tar'));
let lock;
for (let offset = 0; offset + 512 <= archive.length;) {
  const header = archive.subarray(offset, offset + 512);
  if (header.every(x => x === 0)) break;
  const text = (start, length) => header.subarray(start, start + length).toString('utf8').split('\0')[0];
  const name = text(0, 100);
  const prefix = text(345, 155);
  const full = `${prefix ? `${prefix}/` : ''}${name}`.replace(/^\.\//, '');
  const size = parseInt(text(124, 12).trim(), 8);
  assert.ok(Number.isSafeInteger(size) && size >= 0 && size <= 1024 * 1024);
  assert.ok(offset + 512 + size <= archive.length);
  if (full === 'Cargo.lock') {
    assert.ok(header[156] === 0 || header[156] === 48, 'lock must be a regular file');
    assert.equal(lock, undefined, 'duplicate lock entry');
    lock = archive.subarray(offset + 512, offset + 512 + size);
  }
  offset += 512 + Math.ceil(size / 512) * 512;
}
assert.ok(lock && lock.toString('utf8').startsWith('# This file is automatically @generated by Cargo.'));
const targetDir = resolve(local, 'lock-export');
const target = resolve(targetDir, 'Cargo.lock');
assert.equal(dirname(target), targetDir);
await mkdir(targetDir, { recursive: true });
await writeFile(target, lock, { flag: 'wx' });
console.log('Extracted only generated Cargo.lock; existing files were not overwritten.');
